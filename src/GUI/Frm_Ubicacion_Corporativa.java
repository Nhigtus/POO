    private void configurarTabla() {
        String[] columnas = {"ID País", "País", "ID Ciudad", "Ciudad", "Referencia"};
        modeloTabla = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        tblUbicaciones.setModel(modeloTabla);
    }

    private void cargarTabla() {
        modeloTabla.setRowCount(0);
        for (Ubicacion_Corporativa u : Controlador_UbicacionCorporativa.arregloUC) {
            modeloTabla.addRow(new Object[]{
                u.getIdPais(), u.getNombrePais(), u.getIdCiudad(),
                u.getNombreCiudad(), u.getReferenciaPais()
            });
        }
    }

    private void limpiar() {
        txtIdPais.setText("");
        txtNombrePais.setText("");
        txtIdCiudad.setText("");
        txtNombreCiudad.setText("");
        txtReferencia.setText("");
        tblUbicaciones.clearSelection();
        txtIdPais.requestFocus();
    }

    private void mostrarUbicacion(Ubicacion_Corporativa u) {
        txtIdPais.setText(String.valueOf(u.getIdPais()));
        txtNombrePais.setText(u.getNombrePais());
        txtIdCiudad.setText(String.valueOf(u.getIdCiudad()));
        txtNombreCiudad.setText(u.getNombreCiudad());
        txtReferencia.setText(u.getReferenciaPais());
    }

    // Devuelve una ubicación "llave" solo con el ID de ciudad
    private Ubicacion_Corporativa leerSoloIdCiudad() {
        try {
            Ubicacion_Corporativa u = new Ubicacion_Corporativa();
            u.setIdCiudad(Integer.parseInt(txtIdCiudad.getText().trim()));
            return u;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID de la ciudad debe ser un número entero.",
                    "Dato inválido", JOptionPane.WARNING_MESSAGE);
            txtIdCiudad.requestFocus();
            return null;
        }
    }

    // Lee y valida todo el formulario
    private Ubicacion_Corporativa leerFormulario() {
        if (txtNombrePais.getText().trim().isEmpty()
                || txtNombreCiudad.getText().trim().isEmpty()
                || txtReferencia.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos.",
                    "Campos vacíos", JOptionPane.WARNING_MESSAGE);
            return null;
        }
        try {
            int idPais = Integer.parseInt(txtIdPais.getText().trim());
            int idCiudad = Integer.parseInt(txtIdCiudad.getText().trim());
            if (idPais <= 0 || idCiudad <= 0) {
                JOptionPane.showMessageDialog(this, "Los IDs deben ser mayores que cero.",
                        "Dato inválido", JOptionPane.WARNING_MESSAGE);
                return null;
            }
            return new Ubicacion_Corporativa(idPais, txtNombrePais.getText().trim(),
                    idCiudad, txtNombreCiudad.getText().trim(),
                    txtReferencia.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "ID País e ID Ciudad deben ser números enteros.",
                    "Dato inválido", JOptionPane.WARNING_MESSAGE);
            return null;
        }
    }

    // Si el país ya existe, devuelve su nombre registrado (para mantener coherencia)
    private String nombrePaisRegistrado(int idPais) {
        for (Ubicacion_Corporativa u : Controlador_UbicacionCorporativa.arregloUC) {
            if (u.getIdPais() == idPais) {
                return u.getNombrePais();
            }
        }
        return null;
    }
