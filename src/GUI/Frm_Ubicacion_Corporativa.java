    private void tbnInstertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tbnInstertarActionPerformed
        Ubicacion_Corporativa u = leerFormulario();
        if (u == null) return;

        // Un mismo ID de país debe tener siempre el mismo nombre
        String nombreExistente = nombrePaisRegistrado(u.getIdPais());
        if (nombreExistente != null && !nombreExistente.equalsIgnoreCase(u.getNombrePais())) {
            JOptionPane.showMessageDialog(this,
                    "El ID de país " + u.getIdPais() + " ya pertenece a \"" + nombreExistente + "\".",
                    "País inconsistente", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (cont.insertar(u)) {
            cargarTabla();
            limpiar();
            JOptionPane.showMessageDialog(this, "¡Ubicación registrada con éxito!");
        } else {
            JOptionPane.showMessageDialog(this,
                    "Ya existe una ciudad con el ID " + u.getIdCiudad() + ".",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_tbnInstertarActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        Ubicacion_Corporativa llave = leerSoloIdCiudad();
        if (llave == null) return;

        Ubicacion_Corporativa encontrada = (Ubicacion_Corporativa) cont.consultarUno(llave);
        if (encontrada != null) {
            mostrarUbicacion(encontrada);
        } else {
            JOptionPane.showMessageDialog(this, "Ciudad no encontrada.",
                    "Sin resultados", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void tbnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tbnActualizarActionPerformed
       Ubicacion_Corporativa u = leerFormulario();
        if (u == null) return;

        Object resultado = cont.update(u);   // se busca por ID de ciudad
        if (resultado != null) {
            cargarTabla();
            limpiar();
            JOptionPane.showMessageDialog(this, "Ubicación actualizada.");
        } else {
            JOptionPane.showMessageDialog(this,
                    "No existe una ciudad con el ID " + u.getIdCiudad() + ".",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_tbnActualizarActionPerformed

    private void txtEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtEliminarActionPerformed
        Ubicacion_Corporativa llave = leerSoloIdCiudad();
        if (llave == null) return;

        Ubicacion_Corporativa encontrada = (Ubicacion_Corporativa) cont.consultarUno(llave);
        if (encontrada == null) {
            JOptionPane.showMessageDialog(this, "Ciudad no encontrada.",
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        int op = JOptionPane.showConfirmDialog(this,
                "¿Eliminar la ciudad \"" + encontrada.getNombreCiudad() + "\"?",
                "Confirmar", JOptionPane.YES_NO_OPTION);
        if (op == JOptionPane.YES_OPTION) {
            cont.delete(encontrada);
            cargarTabla();
            limpiar();
        }
    }//GEN-LAST:event_txtEliminarActionPerformed

