    private void tblProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductosMouseClicked
        int f = tblProductos.getSelectedRow();
        if (f < 0) return;
        txtId.setText(modeloTabla.getValueAt(f, 0).toString());
        txtSku.setText(modeloTabla.getValueAt(f, 1).toString());
        txtNombre.setText(modeloTabla.getValueAt(f, 2).toString());
        txtDescripcion.setText(modeloTabla.getValueAt(f, 3).toString());
        txtPrecio.setText(modeloTabla.getValueAt(f, 4).toString());
        txtStock.setText(modeloTabla.getValueAt(f, 5).toString());
        txtProveedor.setText(modeloTabla.getValueAt(f, 6).toString());
        cmbTipo.setSelectedItem(modeloTabla.getValueAt(f, 7).toString());
           Producto llave = new Producto();
   llave.setId(Integer.parseInt(txtId.getText().trim()));
   Producto encontrado = (Producto) cont.consultarUno(llave);
   if (encontrado instanceof ProductoPerecedero) {
       txtFechaCaducidad.setText(((ProductoPerecedero) encontrado).getFechaCaducidad());
   } else {
       txtFechaCaducidad.setText("");
   }
    }//GEN-LAST:event_tblProductosMouseClicked

    private void btnInsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInsertarActionPerformed
        Producto p = leerFormulario();
        if (p == null) return;

        if (cont.insertar(p)) {
            cargarTabla();
            limpiar();
            JOptionPane.showMessageDialog(this, "¡Producto registrado con éxito!");
        } else {
            JOptionPane.showMessageDialog(this,
                    "Ya existe un producto con el ID " + p.getId() + ".",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnInsertarActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        Producto llave = leerSoloId();
        if (llave == null) return;

        Producto encontrado = (Producto) cont.consultarUno(llave);
        if (encontrado != null) {
            mostrarProducto(encontrado);
        } else {
            JOptionPane.showMessageDialog(this, "Producto no encontrado.",
                    "Sin resultados", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
           Producto p = leerFormulario();
   if (p == null) return;

   if (cont.update(p) != null) {
       cargarTabla();
       limpiar();
       JOptionPane.showMessageDialog(this, "¡Producto actualizado con éxito!");
   } else {
       JOptionPane.showMessageDialog(this,
               "No existe un producto con el ID " + p.getId() + ".",
               "Error", JOptionPane.ERROR_MESSAGE);
   }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        Producto llave = leerSoloId();
        if (llave == null) return;

        Producto encontrado = (Producto) cont.consultarUno(llave);
        if (encontrado == null) {
            JOptionPane.showMessageDialog(this, "Producto no encontrado.",
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        int op = JOptionPane.showConfirmDialog(this,
                "¿Eliminar \"" + encontrado.getNombre() + "\"?",
                "Confirmar", JOptionPane.YES_NO_OPTION);
        if (op == JOptionPane.YES_OPTION) {
            cont.delete(encontrado);
            cargarTabla();
            limpiar();
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

