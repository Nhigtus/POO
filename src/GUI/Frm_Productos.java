    private void cargarTabla() {
        modeloTabla.setRowCount(0);
        for (Producto p : Controlador_Productos.arregloProductos) {
            modeloTabla.addRow(new Object[]{
                p.getId(), p.getCodigoSKU(), p.getNombre(), p.getDescripción(),
                p.getPrecio_unitario(), p.getStock_actual(),
                p.getProveedor(), p.getTipo(), p.getInfoAdicional()
            });
        } 
    }
    
    private void limpiar() {
        txtId.setText("");
        txtSku.setText("");
        txtNombre.setText("");
        txtDescripcion.setText("");
        txtPrecio.setText("");
        txtStock.setText("");
        txtProveedor.setText("");
        cmbTipo.setSelectedIndex(0);
        txtFechaCaducidad.setText("");
        tblProductos.clearSelection();
        txtId.requestFocus();
    }
    
    private void mostrarProducto(Producto p) {
        txtId.setText(String.valueOf(p.getId()));
        txtSku.setText(p.getCodigoSKU());
        txtNombre.setText(p.getNombre());
        txtDescripcion.setText(p.getDescripción());
        txtPrecio.setText(String.valueOf(p.getPrecio_unitario()));
        txtStock.setText(String.valueOf(p.getStock_actual()));
        txtProveedor.setText(p.getProveedor());
        cmbTipo.setSelectedItem(p.getTipo());
         if (p instanceof ProductoPerecedero) {
       txtFechaCaducidad.setText(((ProductoPerecedero) p).getFechaCaducidad());
   } else {
       txtFechaCaducidad.setText("");
   }
    }
    
    // Lee el ID y devuelve un Producto "llave" para buscar/eliminar
    private Producto leerSoloId() {
        try {
            Producto p = new Producto();
            p.setId(Integer.parseInt(txtId.getText().trim()));
            return p;
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID debe ser un número entero.",
                    "Dato inválido", JOptionPane.WARNING_MESSAGE);
            txtId.requestFocus();
            return null;
        }
    }
    
    // Lee y valida todo el formulario. Devuelve null si algo está mal
    private Producto leerFormulario() {
    if (txtSku.getText().trim().isEmpty() || txtNombre.getText().trim().isEmpty()
            || txtDescripcion.getText().trim().isEmpty()
            || txtProveedor.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Complete todos los campos.",
                "Campos vacíos", JOptionPane.WARNING_MESSAGE);
        return null;
    }
    try {
        int id = Integer.parseInt(txtId.getText().trim());
        float precio = Float.parseFloat(txtPrecio.getText().trim().replace(',', '.'));
        int stock = Integer.parseInt(txtStock.getText().trim());

        if (precio < 0 || stock < 0) {
            JOptionPane.showMessageDialog(this, "Precio y stock no pueden ser negativos.",
                    "Dato inválido", JOptionPane.WARNING_MESSAGE);
            return null;
        }

        String tipo = cmbTipo.getSelectedItem().toString();
        if (tipo.equals("Perecedero")) {
            String fecha = txtFechaCaducidad.getText().trim();
            if (fecha.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Digite la fecha de caducidad (DD/MM/AAAA).",
                        "Campo vacío", JOptionPane.WARNING_MESSAGE);
                return null;
            }
            return new ProductoPerecedero(id, txtSku.getText().trim(), txtNombre.getText().trim(),
                    txtDescripcion.getText().trim(), precio, stock,
                    txtProveedor.getText().trim(), tipo, fecha);
        }
        
        return new Producto(id, txtSku.getText().trim(), txtNombre.getText().trim(),
                txtDescripcion.getText().trim(), precio, stock,
                txtProveedor.getText().trim(), tipo);

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "ID y Stock deben ser enteros y Precio debe ser numérico.",
                "Dato inválido", JOptionPane.WARNING_MESSAGE);
        return null;
    }
}
